"""Throw-away test: match an image against every reference card image (image-to-image) using CLIP.

Usage: python test_inference.py <image> [--top 10] [--model name-or-path] [--db path]
"""
import argparse
import os
import sqlite3

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
from transformers import CLIPModel, CLIPProcessor

base_dir = os.path.dirname(os.path.abspath(__file__))

parser = argparse.ArgumentParser()
parser.add_argument("image")
parser.add_argument("--top", type=int, default=10)
parser.add_argument("--model", default="openai/clip-vit-base-patch32")
parser.add_argument("--db", default=os.path.join(base_dir, "dataset.db"))
args = parser.parse_args()

def resize_image(image):
    # Fill transparent corners with a solid background
    if (image.mode in ("RGBA", "LA", "P")):
        image = image.convert("RGBA")
        background = Image.new("RGB", image.size, (0, 0, 0))
        background.paste(image, mask=image.getchannel("A"))
        image = background
    else:
        image = image.convert("RGB")

    return image.resize((224, 224), Image.Resampling.LANCZOS)

def features(out):
    return out if isinstance(out, torch.Tensor) else out.pooler_output

device = "cuda" if torch.cuda.is_available() else "cpu"
dtype = torch.float16 if device == "cuda" else torch.float32
model = CLIPModel.from_pretrained(args.model).to(device, dtype).eval()
processor = CLIPProcessor.from_pretrained(args.model)

# Reference embeddings for every face of every printing are generated by build_combined_data.py
db = sqlite3.connect(args.db)
metadata = dict(db.execute("SELECT key, value FROM metadata"))
assert metadata["embedding_model"] == args.model, f"Database embeddings were made with {metadata['embedding_model']}"

names = []
paths = []
embeddings = []
for name, front_path, front_embedding, back_path, back_embedding in db.execute(
        "SELECT name, front_image_path, front_embedding, back_image_path, back_embedding FROM cards"):
    for path, embedding in ((front_path, front_embedding), (back_path, back_embedding)):
        if (embedding is not None):
            names.append(name)
            paths.append(os.path.join(base_dir, path))
            embeddings.append(embedding)

reference_embeds = torch.from_numpy(np.frombuffer(b"".join(embeddings), dtype="<f2").reshape(len(embeddings), -1).copy()).to(device, dtype)

with torch.no_grad():
    inputs = processor(images=resize_image(Image.open(args.image)), return_tensors="pt")
    image_embed = F.normalize(features(model.get_image_features(pixel_values=inputs["pixel_values"].to(device, dtype))), dim=-1)

similarity = (image_embed @ reference_embeds.T).squeeze(0).float()

# Each card name is scored by its best matching printing, and the softmax is taken over names
# so cards with many printings don't soak up probability
unique_names = sorted(set(names))
name_index = {name: i for i, name in enumerate(unique_names)}
reference_name_idx = torch.tensor([name_index[name] for name in names], device=device)
name_scores = torch.full((len(unique_names),), -1.0, device=device).scatter_reduce(0, reference_name_idx, similarity, "amax")
probs = (name_scores * model.logit_scale.exp().float()).softmax(dim=0)

results = []
seen = set()
for idx in similarity.argsort(descending=True).tolist():
    if (names[idx] not in seen):
        seen.add(names[idx])
        results.append((similarity[idx].item(), probs[name_index[names[idx]]].item(), names[idx], paths[idx]))
        if (len(results) >= args.top):
            break

print(f"\nTop {args.top} matches for {args.image}:")
for rank, (score, prob, name, path) in enumerate(results, start=1):
    print(f"{rank:2d}. {score:.4f}  (p={prob:.3f})  {name}  ({os.path.relpath(path, base_dir)})")
